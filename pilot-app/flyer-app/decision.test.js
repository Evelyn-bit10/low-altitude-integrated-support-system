'use strict';
const assert = require('node:assert/strict');
const { evaluate, environment, stands } = require('./decision.js');
const aircraft = { rid_lost: false, emergency: false, reg_no: 'R', ua_id: 'U', battery_pct: 60, link_quality: 4 };
const weather = { visibility: 5000, cloud_base_agl: 500, wind_speed: 5, gust: 8 };
function check(level, uav, meteo) { assert.equal(evaluate(uav, meteo).level, level); }
check('APPROVE', aircraft, weather);
check('DENY', { ...aircraft, rid_lost: true }, weather);
check('HOLD', { ...aircraft, rid_lost: undefined }, weather);
check('DENY', { ...aircraft, battery_pct: 24.9 }, weather);
check('HOLD', { ...aircraft, battery_pct: 25 }, weather);
check('APPROVE', { ...aircraft, battery_pct: 45 }, weather);
check('HOLD', { ...aircraft, battery_pct: null }, weather);
check('DENY', { ...aircraft, link_quality: 2 }, weather);
check('HOLD', { ...aircraft, link_quality: 3 }, weather);
check('DENY', aircraft, { ...weather, visibility: 1599 });
check('APPROVE', aircraft, { ...weather, visibility: 1600, cloud_base_agl: 120, wind_speed: 6, gust: 10 });
check('HOLD', aircraft, { ...weather, wind_speed: 8 });
check('DENY', aircraft, { ...weather, wind_speed: 8.1 });
check('HOLD', aircraft, { ...weather, cloud_base_agl: null });
check('DENY', { ...aircraft, emergency: true }, {});
check('DENY', null, weather);
const loc = { lat: 0, lon: 0, alt_msl: 100 };
const zone = { active: true, name: '测试', floor_msl: 100, ceiling_msl: 200, polygon: [[0, 0], [0, 1], [1, 1], [1, 0]] };
const obstacle = { id: 'O1', active: true, name: '测试', lat: 0, lon: 0, top_msl: 100, radius: 10, buffer: 5 };
assert.equal(environment(loc, { airspaces: [zone], obstacles: [] }).level, 'DENY');
assert.equal(environment({ ...loc, alt_msl: 99 }, { airspaces: [zone], obstacles: [] }).level, 'APPROVE');
assert.equal(environment(loc, { airspaces: [], obstacles: [obstacle] }).level, 'DENY');
assert.deepEqual(environment(loc, { airspaces: [], obstacles: [obstacle] }).obstacleHits.map((hit) => hit.id), ['O1']);
assert.equal(environment(loc, { airspaces: [], obstacles: [{ ...obstacle, id: null }] }).level, 'HOLD');
assert.deepEqual(environment(loc, { airspaces: [], obstacles: [{ ...obstacle, active: false }] }).obstacleHits, []);
assert.equal(environment({ ...loc, alt_msl: 101 }, { airspaces: [], obstacles: [obstacle] }).level, 'APPROVE');
assert.equal(environment(loc, { airspaces: [{ ...zone, active: false }], obstacles: [{ ...obstacle, active: false }] }).level, 'APPROVE');
assert.equal(environment(loc, { airspaces: [zone], obstacles: [{ ...obstacle, buffer: null }] }).level, 'DENY');
assert.equal(environment(loc, { airspaces: [], obstacles: [{ ...obstacle, buffer: null }] }).level, 'HOLD');
assert.equal(environment({ ...loc, lat: null }, { airspaces: [], obstacles: [] }).level, 'HOLD');
assert.equal(environment(loc, {}).level, 'HOLD');
const now = Date.parse('2026-11-22T08:00:00Z');
const ground = { airport_code: 'SITE-A', data_source: 'demo', generated_at: new Date(now).toISOString(), stands: [{ status: 'free' }] };
assert.equal(stands('SITE-A', ground, now).level, 'APPROVE');
assert.equal(stands('SITE-B', ground, now).level, 'HOLD');
assert.equal(stands('', ground, now).level, 'HOLD');
assert.equal(stands('SITE-A', { ...ground, airport_code: '' }, now).level, 'HOLD');
assert.equal(stands('SITE-A', { ...ground, data_source: null }, now).level, 'HOLD');
assert.equal(stands('SITE-A', { ...ground, generated_at: '2026-11-22T08:00:00' }, now).level, 'HOLD');
assert.equal(stands('SITE-A', { ...ground, stands: [] }, now).level, 'HOLD');
assert.equal(stands('SITE-A', { ...ground, stands: [{ status: 'unknown' }] }, now).level, 'HOLD');
assert.equal(stands('SITE-A', { ...ground, generated_at: new Date(now - 60001).toISOString() }, now).level, 'HOLD');
assert.equal(stands('SITE-A', { ...ground, generated_at: new Date(now + 30001).toISOString() }, now).level, 'HOLD');
console.log('演示共用规则测试通过');
